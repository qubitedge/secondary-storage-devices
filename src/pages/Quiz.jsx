export default function Quiz() {
  const [currentIdx, setCurrentIdx] = useState(0);
  const [score, setScore] = useState(0);
  const [selectedOption, setSelectedOption] = useState(null);
  const [isFinished, setIsFinished] = useState(false);

  const currentQ = questions[currentIdx];

  const handleSelect = (option) => {
    if (selectedOption !== null) return;
    setSelectedOption(option);
    if (option === currentQ.answer) {
      setScore(prev => prev + 1);
    }
  };

  const handleNext = () => {
    if (currentIdx === questions.length - 1) {
      setIsFinished(true);
    } else {
      setCurrentIdx(prev => prev + 1);
      setSelectedOption(null);
    }
  };

  const handleRestart = () => {
    setCurrentIdx(0);
    setScore(0);
    setSelectedOption(null);
    setIsFinished(false);
  };

  if (isFinished) {
    const percentage = Math.round((score / questions.length) * 100);
    let title = 'Storage Novice';
    let msg = 'Good effort! Review the component labs and try again.';
    if (percentage >= 80) {
      title = 'Master Storage Architect 🏆';
      msg = 'Exceptional understanding of magnetic, flash, optical, and archival secondary storage systems!';
    } else if (percentage >= 60) {
      title = 'Storage Specialist ⭐';
      msg = 'Solid grasp of core storage principles and hardware architectures.';
    }

    return (
      <div className="page quiz-page">
        <div className="quiz-card result-mode">
          <div className="eyebrow">ASSESSMENT COMPLETE</div>
          <div className="score-circle">
            <span className="score-num">{score} / {questions.length}</span>
            <span className="score-pct">{percentage}%</span>
          </div>
          <h2>{title}</h2>
          <p className="result-msg">{msg}</p>

          <div className="quiz-actions">
            <button className="primary" onClick={handleRestart}>
              Retake Assessment ↻
            </button>
            <Link to="/en/explore" className="ghost">
              Review Components ↗
            </Link>
            <Link to="/en" className="ghost subtle">
              Back to Home
            </Link>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="page quiz-page">
      <div className="quiz-card">
        <div className="quiz-top-bar">
          <div className="eyebrow">
            QUESTION {currentIdx + 1} OF {questions.length}
          </div>
          <div className="progress-bar-wrap">
            <div 
              className="progress-fill" 
              style={{ width: `${((currentIdx + 1) / questions.length) * 100}%` }}
            ></div>
          </div>
        </div>

        <h2 className="quiz-question">{currentQ.q}</h2>

        <div className="quiz-options">
          {currentQ.options.map((opt) => {
            let stateClass = '';
            if (selectedOption !== null) {
              if (opt === currentQ.answer) {
                stateClass = 'correct';
              } else if (opt === selectedOption) {
                stateClass = 'wrong';
              }
            }

            return (
              <button
                key={opt}
                className={`quiz-option-btn ${stateClass}`}
                onClick={() => handleSelect(opt)}
                disabled={selectedOption !== null}
              >
                <span className="opt-indicator">
                  {stateClass === 'correct' ? '✓' : stateClass === 'wrong' ? '✕' : ''}
                </span>
                <span className="opt-text">{opt}</span>
              </button>
            );
          })}
        </div>

        {selectedOption !== null && (
          <div className="quiz-explanation-box">
            <b>{selectedOption === currentQ.answer ? '🎉 Correct!' : '💡 Explanation:'}</b>
            <p>{currentQ.explanation}</p>
          </div>
        )}

        {selectedOption !== null && (
          <div className="quiz-footer">
            <button className="primary next-btn" onClick={handleNext}>
              {currentIdx === questions.length - 1 ? 'View Results ↗' : 'Next Question →'}
            </button>
          </div>
        )}
      </div>
    </div>
  );
}
